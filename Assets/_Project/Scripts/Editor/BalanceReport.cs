using System.Collections.Generic;
using System.IO;
using System.Text;
using UnityEditor;
using UnityEngine;

namespace EchoChamber.Editor
{
    /// <summary>Runs the scripted policies headless over many seeds and writes docs/BALANCE.md.</summary>
    public static class BalanceReport
    {
        [MenuItem("Echo Chamber/Write Balance Report")]
        public static void Write()
        {
            var asset = AssetDatabase.LoadAssetAtPath<GameContent>(ContentImporter.ContentAssetPath);
            var tuning = AssetDatabase.LoadAssetAtPath<TuningConfig>(ContentImporter.TuningAssetPath);
            const int seeds = 100;
            var sb = new StringBuilder();
            sb.AppendLine("# Balance report (headless)");
            sb.AppendLine();
            sb.AppendLine($"Generated by `Echo Chamber/Write Balance Report`. {seeds} seeds per policy, full 3-day game, decisions applied by scripted policies (`PolicyLibrary`).");
            sb.AppendLine();
            sb.AppendLine("| Policy | Sleep | Locked | Alive | Balance | Gentry | Rev D1 | Rev D2 | Rev D3 | Coesao | Tensao | Apatia | Percebido | Goals |");
            sb.AppendLine("|---|---|---|---|---|---|---|---|---|---|---|---|---|---|");
            var reached = new HashSet<EndingId>();
            foreach (var policy in PolicyLibrary.All())
            {
                var counts = new Dictionary<EndingId, int>();
                double[] rev = new double[3];
                double coe = 0, ten = 0, apa = 0, goals = 0, und = 0;
                for (int s = 1; s <= seeds; s++)
                {
                    var r = HeadlessRunner.Run(asset.content, tuning.data, policy, s);
                    counts.TryGetValue(r.Ending, out int c);
                    counts[r.Ending] = c + 1;
                    for (int d = 0; d < 3; d++) rev[d] += r.RevenueByDay[d];
                    coe += r.Cohesion; ten += r.Tension; apa += r.Apathy; und += r.Understanding;
                    goals += (double)r.GoalsAchieved / r.GoalsTotal;
                    reached.Add(r.Ending);
                }
                int Get(EndingId e) => counts.TryGetValue(e, out int v) ? v : 0;
                sb.AppendLine($"| {policy.Name} | {Get(EndingId.Sleep)} | {Get(EndingId.Locked)} | {Get(EndingId.Alive)} | {Get(EndingId.Balance)} | {Get(EndingId.Gentry)} | " +
                              $"{rev[0] / seeds:F0} | {rev[1] / seeds:F0} | {rev[2] / seeds:F0} | {coe / seeds:P0} | {ten / seeds:P0} | {apa / seeds:P0} | {und / seeds:P0} | {goals / seeds:P0} |");
            }
            sb.AppendLine();
            sb.AppendLine("Endings reached by at least one policy: " + string.Join(", ", reached) + $" ({reached.Count}/5).");
            sb.AppendLine();
            sb.AppendLine("Targets per day: 140, 220, 260 EUR. Goals are counted per day (revenue target, bookshop open on day 2, tension below 70%).");
            File.WriteAllText(Path.Combine(Path.GetDirectoryName(Application.dataPath), "docs", "BALANCE.md"), sb.ToString());
            Debug.Log("[EchoChamber] Balance report written. Endings reached: " + reached.Count + "/5");
        }
    }
}
